import { moisUrssaf, etatUrssaf, echeance } from "@/lib/urssafRappel";
let ok = 0, ko = 0;
const v = (c, m) => { if (c) { ok++; } else { ko++; console.log("✗ " + m); } };
const fait = { "2026-06": "x", "2026-07": "x", "2026-08": "x", "2026-09": "x" };
const le29 = new Date(2026, 9, 29, 18);
v(echeance("2026-10").getDate() === 30 && echeance("2026-10").getMonth() === 10, "octobre → avant le 30 novembre");
v(echeance("2026-12").getFullYear() === 2027 && echeance("2026-12").getDate() === 31, "décembre → 31 janvier");
let e = etatUrssaf(fait, le29);
v(e.urgents.length === 0, "29/10 tout payé : rien d'urgent");
v(e.suivant.mois === "2026-10" && e.suivant.rappel.getDate() === 23 && e.suivant.rappel.getMonth() === 10, "prochain = octobre, rappel le 23 novembre");
v(e.dernierFait.mois === "2026-09", "dernier réglé = septembre");
e = etatUrssaf(fait, new Date(2026, 10, 22, 12));
v(e.urgents.length === 0, "22 novembre : pas encore de rappel");
e = etatUrssaf(fait, new Date(2026, 10, 23, 9));
v(e.urgents.length === 1 && e.urgents[0].mois === "2026-10" && e.urgents[0].jours === 7, "23 novembre : rappel octobre, 7 jours");
e = etatUrssaf(fait, new Date(2026, 11, 1, 9));
v(e.urgents[0]?.etat === "retard", "1er décembre sans validation : retard");
e = etatUrssaf({ ...fait, "2026-10": "x" }, new Date(2026, 10, 25));
v(e.urgents.length === 0 && e.suivant.mois === "2026-11", "octobre validé → suivant novembre");
v(moisUrssaf({}, le29).filter((x) => x.etat === "retard").length === 3, "sans rien validé au 29/10 : juin, juillet, août en retard");
console.log(`${ok}/${ok + ko} vérifications au vert`);
if (ko) process.exit(1);
